use serde::{Deserialize, Serialize};

/// HTTP gateway configuration.
///
/// The gateway runs two listeners:
///
/// * **Admin** on TCP (`bind_address`:`port`) with bearer-token auth
///   for the REST surface (config / status / jobs / cron / memory /
///   traces / skills / tools / llm and a read-only channel list) and
///   channel-token auth for the co-hosted `/v1/channel-ws` upgrade.
///   The TUI and the browser-side web chat page both dial this same
///   bind.
/// * **Channel** on loopback TCP (`127.0.0.1:<ephemeral>`, hardcoded
///   — not configurable) with channel-token auth backed by the
///   gateway's `ChannelTokenTable` (per-spawn subprocess capability
///   tokens). Used only by gateway-spawned sidecars; the chosen port
///   is published to `<workspace>/state/channel.port` and handed to
///   each child via its launch URL. Mounts the same `/v1/channel-ws`
///   endpoint the admin listener exposes.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(default)]
pub struct GatewayConfig {
    /// When false, `baybo gateway start` still runs, but the service unit
    /// generated by `install`/`enable` warns that the section is disabled.
    pub enabled: bool,
    /// Admin TCP listener bind address.
    pub bind_address: String,
    /// Admin TCP listener port.
    pub port: u16,
    /// CORS origins permitted by the admin listener. Empty = no
    /// CORS headers emitted. CORS is meaningless on the loopback
    /// channel listener and is not applied there.
    pub cors_allowed_origins: Vec<String>,
    /// Seconds the process waits for graceful shutdown before the
    /// force-exit watchdog kicks in.
    pub shutdown_grace_secs: u64,
    /// Direct-reachability advertisement for paired iOS devices. The app
    /// tries these endpoints before falling back to the operator relay, so
    /// the common "phone + server on the same network" case stays off the
    /// relay. Handed to the device inside the SPAKE2 K-channel at pairing
    /// (`GatewayWelcome.direct_candidates`).
    pub direct: DirectConfig,
    /// Blind remote-host push: when enabled, A POSTs an operator-encrypted
    /// lock-screen preview to the remote host (C) on every real user turn.
    pub push: PushConfig,
}

/// A-side direct-reachability config (the `direct` block in `baybo.json`).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
#[serde(default)]
pub struct DirectConfig {
    /// When false, no direct candidates are advertised — pairing devices fall
    /// straight to the relay.
    pub enabled: bool,
    /// Endpoints A is reachable at directly (LAN / Tailscale / reverse proxy),
    /// e.g. `["wss://baybo.lan:8889", "wss://baybo.tailnet.ts.net:8889"]`.
    pub advertise: Vec<String>,
}

/// A-side push config (the `push` block in `baybo.json`). A holds only the
/// remote-host URL + its per-instance admission key — never the `.p8`, which
/// lives solely in C.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
#[serde(default)]
pub struct PushConfig {
    /// When false, no push dispatcher runs.
    pub enabled: bool,
    /// The remote host's base URL, e.g. `https://remote.baybo.example`.
    pub gateway_url: String,
    /// Per-instance admission key C validates on every `/notify`.
    pub instance_key: String,
}

impl Default for GatewayConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            bind_address: "127.0.0.1".into(),
            port: 8888,
            cors_allowed_origins: Vec::new(),
            shutdown_grace_secs: 30,
            direct: DirectConfig::default(),
            push: PushConfig::default(),
        }
    }
}
